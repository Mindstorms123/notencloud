/// Provides publisher, arranger, original instrumentation notes,
/// order number and verified direct online links for sheet music in the repertoire.
class EditionInfo {
  final String title;
  final String publisher;
  final String arranger;
  final String series;
  final String orderNumber;
  final String? directUrl;
  final String instrumentationNote;
  final List<String> naturallyMissingInstruments; // Instruments never included in this edition

  const EditionInfo({
    required this.title,
    this.publisher = '',
    this.arranger = '',
    this.series = '',
    this.orderNumber = '',
    this.directUrl,
    this.instrumentationNote = '',
    this.naturallyMissingInstruments = const [],
  });

  bool get hasDirectUrl => directUrl != null && directUrl!.isNotEmpty;
}

